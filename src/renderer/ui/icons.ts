/**
 * Return an inline SVG string for `name`, sized `size`×`size` (default 16).
 * Uses `currentColor` so the icon inherits the parent element's text color.
 */
export function icon(name: IconName, size = 16): string {
  const inner = ICON_PATHS[name] ?? '';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" ` +
    `viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
    `stroke-linecap="round" stroke-linejoin="round" class="ui-icon" aria-hidden="true">${inner}</svg>`
  );
}

/** Return a live SVGElement for `name` (handy when you need a node, not a string). */
export function iconEl(name: IconName, size = 16): SVGElement {
  const wrap = document.createElement('div');
  wrap.innerHTML = icon(name, size);
  return wrap.firstElementChild as SVGElement;
}

/** True if `name` is a known icon — lets callers guard dynamic lookups. */
export function isIconName(name: string): name is IconName {
  return Object.prototype.hasOwnProperty.call(ICON_PATHS, name);
}
